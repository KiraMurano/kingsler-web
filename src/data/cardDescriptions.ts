export type Role = 
  | 'Наследник' 
  | 'Казначей' 
  | 'Вор' 
  | 'Шантажист' 
  | 'Рыцарь' 
  | 'Шут';

export type PlotType = 
  | 'Королевский приём' 
  | 'Чёрная книга' 
  | 'Сеть информаторов' 
  | 'Досье' 
  | 'Золотая булла' 
  | 'Тайный заговор';

export type InstantType = 
  | 'Право вето' 
  | 'Перенаправление' 
  | 'Ва-банк' 
  | 'Дворцовый переполох' 
  | 'Шпион' 
  | 'Обвинение в измене';

export type GameCard = Role | PlotType | InstantType;

export type CardCategory = 'role' | 'plot' | 'instant';

export interface CardDescription {
  name: GameCard;
  category: CardCategory;
  title: string;
  badge: string;
  themeColor: string;
  gradient: string;
  borderColor: string;
  artImage: string;
  bottomIcon: string;
  shortDescription: string;
  fullDescription: string;
  strategyTip?: string;
  loreQuote?: string;
  cost: number;
  targeted: boolean;
  blockableBy?: Role;
  blocksRole?: Role;
  copiesCount: number;
}

export const ALL_ROLES: Role[] = [
  'Наследник',
  'Казначей',
  'Вор',
  'Шантажист',
  'Рыцарь',
  'Шут'
];

export const ALL_PLOTS: PlotType[] = [
  'Королевский приём',
  'Чёрная книга',
  'Сеть информаторов',
  'Досье',
  'Золотая булла',
  'Тайный заговор'
];

export const ALL_INSTANTS: InstantType[] = [
  'Право вето',
  'Перенаправление',
  'Ва-банк',
  'Дворцовый переполох',
  'Шпион',
  'Обвинение в измене'
];

export function isRole(card: GameCard): card is Role {
  return ALL_ROLES.includes(card as Role);
}

export function isPlot(card: GameCard): card is PlotType {
  return ALL_PLOTS.includes(card as PlotType);
}

export function isInstant(card: GameCard): card is InstantType {
  return ALL_INSTANTS.includes(card as InstantType);
}


