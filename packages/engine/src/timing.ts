/** Pause so a tabled action can be read before the next beat. */
export const ACTION_HOLD_MS = 2200;

/** Bot thinking before taking their own turn action. */
export const BOT_MOVE_MS = 1600;
export const BOT_MOVE_JITTER_MS = 700;

/** Bot considering a reaction (doubt / block / duel). */
export const BOT_REACTION_MS = 1800;
export const BOT_REACTION_JITTER_MS = 800;

/** Bot considering a veto on a pending effect. */
export const BOT_VETO_MS = 1400;
export const BOT_VETO_JITTER_MS = 600;

/**
 * Окно вето. Открывается на каждое ветируемое действие, независимо от того,
 * держит ли кто-то «Право вето»: пауза одинаковой длины предсказуема, а
 * разная — читается как подсказка о чужих картах.
 *
 * Цена — эта пауза добавляется к каждому действию, так что партия против
 * ботов на неё заметно тяжелеет. Это одно число: если в игре окажется долго,
 * крутить здесь. Начинали с 7 с, в игре оказалось долго.
 */
export const VETO_WINDOW_MS = 5000;

/**
 * Пауза между сбросом и добором при обмене карт руки.
 *
 * Оба движения происходили в одном кадре состояния, и слой карт пружинил их
 * одновременно: на столе это читалось как одно смазанное движение вместо двух.
 * Пауза вычитается из `ACTION_HOLD_MS`, так что ход целиком не удлиняется —
 * меняется только то, как он разбит.
 */
export const EXCHANGE_DRAW_MS = 800;

/**
 * Пауза между стадиями открытия партии.
 *
 * Одна на все переходы, и это не экономия: каждая стадия открытия что-то
 * сообщает — двор собран, ходит такой-то, карты на руках, партия началась, — и
 * сообщению нужно время дойти. Без пауз стадии сменяли друг друга подряд, и
 * открытие читалось как одна суматоха вместо четырёх событий.
 */
export const OPENING_HOLD_MS = 2000;

/**
 * Полёт монетки в жребии: от подброса до приземления, после которого поверх
 * неё встаёт имя первого ходящего.
 */
export const TOSS_SPIN_MS = 2800;

/**
 * Сколько имя победителя жребия стоит на экране, прежде чем начнётся раздача.
 *
 * Это пауза на прочтение, а не на решение: монетка уже легла, и единственное,
 * что здесь происходит, — игрок узнаёт, кто ходит первым.
 */
export const TOSS_VERDICT_MS = OPENING_HOLD_MS;

/**
 * Шаг раздачи: сколько проходит между двумя картами.
 *
 * Раздача — по одной карте по кругу, и шаг делает из неё раздачу, а не
 * появление восьми карт разом. Меньше — карты сливаются в одно движение,
 * больше — стол ждёт вместо того, чтобы начаться.
 */
export const DEAL_STEP_MS = 280;

/**
 * Сколько держится «Битва за престол начинается».
 *
 * Дольше остальных пауз намеренно: это не переход между стадиями, а само
 * объявление — единственное, ради чего стадия существует.
 */
export const FANFARE_MS = 3500;

/**
 * Разброс, с которым боты подтверждают готовность.
 *
 * Разом и мгновенно — это очевидная машина; вразнобой в пределах пары секунд
 * читается как четыре человека, каждый со своим темпом. Ради этого и сделано:
 * на исход не влияет ничего.
 */
export const TOSS_BOT_READY_MS = 2000;
