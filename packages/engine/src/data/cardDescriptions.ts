export type Role =
  | 'Наследник'
  | 'Казначей'
  | 'Вор'
  | 'Шантажист'
  | 'Дуэлянт'
  | 'Шут';

export type PlotType =
  | 'Королевский приём'
  | 'Чёрная книга'
  | 'Сеть информаторов'
  | 'Досье'
  | 'Тайный заговор'
  | 'Стража покоев'
  | 'Охранная грамота';

export type InstantType =
  | 'Право вето'
  | 'Перенаправление'
  | 'Ва-банк'
  | 'Дворцовый переполох'
  | 'Обыск покоев'
  | 'Обвинение в измене';

export type GameCard = Role | PlotType | InstantType;

export type NormalAction =
  | 'Просить содержание'
  | 'Устроить пир'
  | 'Распустить слух'
  | 'Сменить карты';

export type InspectableItem = GameCard | NormalAction;

export type CardCategory = 'role' | 'plot' | 'instant';
export type ItemCategory = CardCategory | 'action';

export interface CardDescription {
  name: InspectableItem;
  category: ItemCategory;
  title: string;
  themeColor: string;
  gradient: string;
  borderColor: string;
  artImage?: string;
  shortDescription: string;
  fullDescription: string;
  strategyTip?: string;
  loreQuote?: string;
  cost: number;
  costTokens?: number;
  costGold?: number;
  targeted: boolean;
  blockableBy?: Role;
  /* Кого эта роль останавливает на дуэли. Список, а не одна роль: Дуэлянт
     держит щит и против Вора, и против Шантажиста. */
  blocksRoles?: Role[];
  copiesCount?: number;
}

export const ALL_ROLES: Role[] = [
  'Наследник',
  'Казначей',
  'Вор',
  'Шантажист',
  'Дуэлянт',
  'Шут'
];

export const ALL_PLOTS: PlotType[] = [
  'Королевский приём',
  'Чёрная книга',
  'Сеть информаторов',
  'Досье',
  'Тайный заговор',
  'Стража покоев',
  'Охранная грамота'
];

export const ALL_INSTANTS: InstantType[] = [
  'Право вето',
  'Перенаправление',
  'Ва-банк',
  'Дворцовый переполох',
  'Обыск покоев',
  'Обвинение в измене'
];

export const ALL_NORMAL_ACTIONS: NormalAction[] = [
  'Просить содержание',
  'Устроить пир',
  'Распустить слух',
  'Сменить карты'
];

export function isRole(card: InspectableItem): card is Role {
  return ALL_ROLES.includes(card as Role);
}

export function isPlot(card: InspectableItem): card is PlotType {
  return ALL_PLOTS.includes(card as PlotType);
}

export function isInstant(card: InspectableItem): card is InstantType {
  return ALL_INSTANTS.includes(card as InstantType);
}

export function isNormalAction(card: InspectableItem): card is NormalAction {
  return ALL_NORMAL_ACTIONS.includes(card as NormalAction);
}

