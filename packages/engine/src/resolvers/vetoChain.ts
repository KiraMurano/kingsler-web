/**
 * Цепочка вето: сколько «Прав вето» сыграно подряд поверх одного действия.
 *
 * Раньше отмена была флагом `isVetoed`, и второе вето поверх первого сыграть
 * было негде — окно потреблялось синхронно. С правилом «вето на вето» отмена
 * стала счётчиком: чётная цепочка означает, что эффект всё-таки применяется,
 * нечётная — что отменён.
 *
 * `isVetoed` остался в состоянии, потому что его читают боты и стол, но теперь
 * он производный. Оба поля пишутся только этими двумя функциями и только
 * вместе: разъехавшись, они дали бы стол, который показывает одно, а делает
 * другое.
 */
export interface VetoChainPatch {
  vetoChain: number;
  isVetoed: boolean;
}

/** Новое действие — цепочка начинается с нуля. */
export function vetoReset(): VetoChainPatch {
  return { vetoChain: 0, isVetoed: false };
}

/** Сыграно ещё одно вето поверх текущей цепочки. */
export function vetoPlayed(currentChain: number): VetoChainPatch {
  const vetoChain = currentChain + 1;
  return { vetoChain, isVetoed: vetoChain % 2 === 1 };
}

/**
 * Чья карта сейчас наверху: последний наложивший вето, а пока вето не было —
 * автор самого действия.
 *
 * Это одно понятие, а не два: наверху лежит то, на что двор отвечает в этом
 * круге, и положил его кто-то один.
 */
export function vetoTopActorId(
  actorId: string,
  overlayInstant: { card: string; actorId: string } | null
): string {
  return overlayInstant?.card === 'Право вето' ? overlayInstant.actorId : actorId;
}

/**
 * Обязан ли игрок ответить в текущем круге окна вето.
 *
 * Правило одно: **у тебя не спрашивают, не хочешь ли ты отменить то, что сам
 * только что положил на стол.** В первом круге наверху лежит действие, и его
 * автор не отвечает — предлагать ему отменить собственный ход значит просить
 * лишний клик на КАЖДОЕ действие партии. Дальше наверху лежит вето, и не
 * отвечает тот, кто его положил: вето на собственное вето не отменяет ничего
 * (чётная цепочка возвращает действие), это просто сожжённая карта.
 *
 * Из-за того, что раньше исключался только автор, положивший вето бот тут же
 * попадал в новый круг и говорил «Не накладываю Вето» сразу после «Право
 * вето!» — отвечал на вопрос, которого ему никто не задавал.
 */
export function vetoAnswerRequired(playerId: string, topActorId: string): boolean {
  return playerId !== topActorId;
}

/**
 * Опрошен ли двор в окне вето: ответили все, кого спрашивали.
 *
 * Окно держится ответами, а не таймером. Таймер закрывал его через
 * фиксированные пять секунд на каждое ветируемое действие — и это была самая
 * дорогая пауза в партии, при том что решение за ней обычно было одно и то же
 * («никто не вмешался»). Опрос стоит ровно столько, сколько думают отвечающие.
 */
export function vetoPollAnswered(
  players: { id: string }[],
  topActorId: string,
  passedIds: string[]
): boolean {
  return !players.some(
    p => vetoAnswerRequired(p.id, topActorId) && !passedIds.includes(p.id)
  );
}
