/**
 * Масштаб интерфейса — и две системы координат, которые из него следуют.
 *
 * Интерфейс нарисован под одно-единственное окно, `DESIGN_WIDTH` × `DESIGN_HEIGHT`
 * логических пикселей, и на любом экране показывается ровно им, целиком
 * отмасштабированным. Не «отзывчивая вёрстка»: на 4K всё вдвое крупнее, чем на
 * 1080p, на телефоне — мельче, но пропорции, плотность и расстановка везде
 * буква в букву одни и те же. Эталон — 1920×1080 при зуме браузера 150%:
 * 1920 / 1.5 = 1280, 1080 / 1.5 = 720.
 *
 * Множитель — вписывание эталона в окно: узкое окно ограничивает шириной,
 * низкое — высотой, и меньше эталона рабочая область не бывает никогда. Он
 * кладётся в `--ui-scale` на корне, а `tokens.css` вешает на него `zoom`.
 *
 * Считает его JS, хотя `min(tan(atan2(100vw, 1280px)), …)` умеет то же самое
 * одной строкой CSS. Так и было сделано сначала — и Safari 26 показывал чёрный
 * экран там, где Chromium показывал игру. Механика `zoom` у обоих движков при
 * замере совпала до пикселя, так что расходилась именно эта арифметика: у
 * WebKit `@supports` на литералах проходит, а выражение с `100vw` и `var()`
 * внутри — уже другой разговор. Деление двух чисел не зависит от того, что
 * движок умеет в `calc()`, и это единственная причина, по которой здесь JS.
 *
 * Отсюда правило, которое стоит держать в голове при любой правке: число,
 * полученное замером, нельзя класть обратно в стиль. `getBoundingClientRect()`
 * и `innerWidth` меряют настоящий экран, то есть уже умноженное, а стиль ждёт
 * макетное — разница ровно в масштаб, и карта улетит мимо якоря, меню встанет
 * мимо карты. Замерять надо через `designRect`, а окно спрашивать у
 * `designViewport`; тогда обе стороны говорят в пикселях макета.
 */

/** Окно, под которое нарисован интерфейс. Крупнее нужно — уменьшайте числа. */
const DESIGN_WIDTH = 1280;
const DESIGN_HEIGHT = 720;

let scale = 1;

/* Читаем применённый `zoom`, а не верим посчитанному. Браузер, не умеющий
   `zoom`, пропустит объявление в `tokens.css` мимо, страница останется в
   масштабе 1 — и делить замеры на желаемый множитель было бы враньём: они
   разошлись бы с раскладкой ровно в него. */
function readBack(): void {
  const applied = Number.parseFloat(getComputedStyle(document.documentElement).zoom);
  scale = Number.isFinite(applied) && applied > 0 ? applied : 1;
}

function apply(): void {
  const wanted = Math.min(window.innerWidth / DESIGN_WIDTH, window.innerHeight / DESIGN_HEIGHT);
  if (!Number.isFinite(wanted) || wanted <= 0) return;
  const root = document.documentElement;
  const text = String(wanted);
  /* Ресайз по одной стороне часто не меняет множителя — `min()` берёт вторую.
     Тогда и трогать ничего не надо: лишняя запись в стиль стоила бы пересчёта
     раскладки на каждое событие ресайза, а их за одно перетаскивание рамки
     окна прилетают десятки. */
  if (root.style.getPropertyValue('--ui-scale') === text) return;
  root.style.setProperty('--ui-scale', text);
  readBack();
}

if (typeof window !== 'undefined') {
  apply();
  /* Ещё раз — перед первым кадром. Первый вызов делается на импорте модуля, а
     он может случиться раньше, чем к документу приложены стили; тогда `zoom`
     ещё не объявлен и обратное чтение вернуло бы единицу. */
  requestAnimationFrame(readBack);

  /* `resize` — это и размер окна, и поворот телефона, и зум браузера, то есть
     всё, от чего масштаб зависит. Приходит он ДО кадровых колбэков, так что
     замеры того же кадра делятся уже на свежий множитель, а не на прошлый.

     Одного будильника хватает, но знать стоит вот что: под эмуляцией размера
     окна в devtools событие не приходит вовсе — `innerWidth` уже новый, а
     интерфейс остался в масштабе прошлого окна. `ResizeObserver` на `html` эту
     дырку не затыкает: он там молчит и на смену окна, и на смену самого
     `zoom`. Настоящее окно так себя не ведёт, и на живой странице пересчёт
     работает; но если однажды масштаб «залипнет» — искать надо здесь. */
  window.addEventListener('resize', apply);
}

/** Во сколько раз экранный пиксель крупнее макетного. */
export function uiScale(): number {
  return scale;
}

/** Экранная длина → длина макета. */
export function toDesign(px: number): number {
  return px / scale;
}

/** `getBoundingClientRect()` в координатах макета. */
export function designRect(node: Element): DOMRect {
  const r = node.getBoundingClientRect();
  return new DOMRect(r.x / scale, r.y / scale, r.width / scale, r.height / scale);
}

/** Окно в координатах макета — то самое, под что нарисована раскладка. */
export function designViewport(): { width: number; height: number } {
  return { width: window.innerWidth / scale, height: window.innerHeight / scale };
}
