/**
 * С каким лицом карту в последний раз показывали двору.
 *
 * Сброс закрыт: `CardPiles` рисует наверху рубашку, листать его нельзя, и лицо
 * карты в сбросе видно ровно один миг — пока она летит в угол. Правило «карта
 * в сбросе — значит открыта» писалось ради одного случая: вскрытая в споре
 * карта не должна переворачиваться обратно, когда исход уходит с экрана. Но
 * оно открывало и те карты, которых никто не видел, — и чужой обмен карт руки
 * показывал двору, что именно сосед выбросил.
 *
 * Отличить одно от другого по одному кадру состояния нельзя: в сбросе обе
 * карты выглядят одинаково. Поэтому лицо помнится — ровно так же, как
 * `handSlotBook` помнит слоты. Карта уносит в могилу то лицо, с которым
 * уходила: показанная остаётся показанной, невиданная так и не открывается.
 *
 * Книга только растёт и никогда не переписывает уже записанное лицо, поэтому
 * `rememberFaces` идемпотентна и при неизменном наборе возвращает тот же
 * объект — это и позволяет `App` держать её в ref и обновлять внутри `useMemo`.
 */
import type { GameCard } from '@kinglier/engine/types';
import type { CardId } from '@kinglier/engine/cardInstance';
import type { PlacedCard } from '../motion/zones.ts';

/** Card id → лицо, с которым карту показывали. Нет записи — не показывали. */
export type FaceBook = Record<CardId, GameCard>;

/** Записать лица, показанные в этой раскладке, поверх прежней книги. */
export function rememberFaces(prev: FaceBook, placed: readonly PlacedCard[]): FaceBook {
  let next: FaceBook | null = null;
  for (const card of placed) {
    const face = card.face.known;
    if (face === null || prev[card.id] === face) continue;
    next ??= { ...prev };
    next[card.id] = face;
  }
  return next ?? prev;
}
