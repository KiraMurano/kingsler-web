/**
 * Под каким углом карта лежит там, где она лежит.
 *
 * Одна функция на весь стол: слой карт (`motion/CardLayer.tsx`) не считает
 * угол сам ни в одной ветке, он спрашивает здесь. Раньше угол выбирался по
 * одной только зоне, и из этого следовали три вещи, которые на столе читались
 * как сбои:
 *
 *  - «Право вето» приходило в ту же лунку и под тем же углом, что и «Ва-банк»,
 *    который оно снимает, — две карты совпадали пиксель в пиксель; то же самое
 *    выходило и у вето со встречным вето, только их уже и по лицу не
 *    различить: разводит их номер звена цепочки;
 *  - вето поверх выкладки Интриги ложилось наискось посреди стола, хотя под
 *    ним ничего нет: интрига в это время уезжает в слот своего игрока;
 *  - все карты ложились строго под одним углом, то есть по линейке, а не рукой.
 *
 * Поэтому угол считается по карте целиком (`PlacedCard`), а не по её зоне, и
 * складывается из двух слагаемых: **посадка** — чем карта занята — и **дрожь**
 * — маленький разброс, свой у каждой карты и неизменный, пока карта та же.
 *
 * Разброс обязан быть детерминированным. `Math.random()` здесь означал бы
 * новый угол на каждом кадре перерисовки: карта, лежащая на столе, тряслась
 * бы вместо того, чтобы лежать. Поэтому он берётся из хеша `CardId` — того
 * самого, которым карта живёт от раздачи до сброса.
 */
import type { CardId } from '@kinglier/engine/cardInstance';
import type { PlacedCard, Zone } from '../motion/zones.ts';
import { tilt } from '../motion/tokens.ts';

/**
 * Шум по карте: число из [0, 1), своё у каждого идентификатора.
 *
 * FNV-1a: короткий, без коллизий на наших идентификаторах (`c0`…`c31`,
 * `overlay:<id>:<карта>`) и, главное, чистый — тот же `id` даёт то же число в
 * любом кадре, в любой вкладке и у любого зрителя. Это и есть условие: всё,
 * что на столе выглядит случайным, обязано быть неизменным для одной карты —
 * иначе оно не «случайное», а дрожащее.
 *
 * Отсюда берут разброс и наклон карты (ниже).
 */
export function cardNoise(id: CardId): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i);
    /* Умножение на 16777619 через сдвиги: в обычном `*` результат уходит за
       53 бита мантиссы и младшие разряды теряются — а именно они здесь и
       различают `c10` от `c11`. */
    h = (h + (h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24)) >>> 0;
  }
  return h / 0x100000000;
}

/** Дрожь руки для этой карты: ±`tilt.laidJitter`, всегда одна и та же. */
export function laidJitter(id: CardId): number {
  return (cardNoise(id) * 2 - 1) * tilt.laidJitter;
}

/**
 * Посадка: угол, под которым карта легла бы, если бы её клали по линейке.
 *
 * `null` — «оставить как лежит»: карта, уходящая в угол стола, не обязана по
 * дороге выпрямляться, это движение, которого никто не просил.
 */
function seat(placed: PlacedCard): number | null {
  const zone: Zone = placed.zone;
  switch (zone.kind) {
    case 'overlay':
      /* Поверх выкладки Интриги вето ложится ровно: оно занимает обычную
         карточную лунку посреди стола, и наклон там не «поперёк действия», а
         просто криво. */
      if (zone.over === 'plot') return 0;
      if (placed.face.known !== 'Право вето') return tilt.overlay;
      /* Чётное звено цепочки ложится накрест нечётного: два вето подряд
         приходят в одну лунку и оба показывают одно лицо. */
      return placed.vetoLink !== undefined && placed.vetoLink % 2 === 0
        ? tilt.overlayVetoCounter
        : tilt.overlayVeto;
    case 'stake':
      return tilt.stake;
    case 'duel':
      return zone.side === 'attacker' ? tilt.duelAttacker : tilt.duelDefender;
    case 'discard':
      return null;
    default:
      return 0;
  }
}

/**
 * Дрожит ли карта в этой зоне.
 *
 * Дрожь — след того, что карту **положили**. Рука её не кладёт, а держит;
 * колода и сброс — это стопки, а не выложенные карты. Всё остальное на столе
 * кто-то куда-то положил, и там дрожь уместна.
 */
function isLaid(kind: Zone['kind']): boolean {
  return kind !== 'hand' && kind !== 'deck' && kind !== 'discard';
}

/**
 * Итоговый угол покоя карты в градусах, или `null`, если угол менять не надо.
 */
export function cardLie(placed: PlacedCard): number | null {
  const base = seat(placed);
  if (base === null) return null;
  return isLaid(placed.zone.kind) ? base + laidJitter(placed.id) : base;
}
