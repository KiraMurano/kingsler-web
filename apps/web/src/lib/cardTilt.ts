/**
 * Наклон карты к курсору — одна формула на все карты сайта.
 *
 * Карта под курсором чуть поворачивается в его сторону: курсор у правого края —
 * карта разворачивается вправо, у верхнего — клонится от зрителя. Приём общий
 * для карт в руке за столом (`motion/CardLayer.tsx`) и для веера на лендинге
 * (`components/CardFanShowcase.tsx`), поэтому и формула общая: копия здесь
 * разошлась бы с оригиналом молча, а «как в игре» — это дословно.
 *
 * Считается всё в долях от полуширины и полувысоты карты, а не в пикселях.
 * Это не мелочь: отношение не зависит от того, каким размером карта вышла на
 * экран, поэтому наклон на 4K, на 1080p и на телефоне одинаковый. Формула в
 * пикселях зависела бы от масштаба — на крупном экране наклон вырождался бы в
 * рывок, на мелком его не было бы вовсе.
 */

/** Прямоугольник карты на экране; подходит `getBoundingClientRect()`. */
export interface TiltBox {
  left: number;
  top: number;
  width: number;
  height: number;
}

/** Углы поворота карты в градусах: `x` — вокруг горизонтали, `y` — вокруг вертикали. */
export interface Tilt {
  x: number;
  y: number;
}

/**
 * `cap` — предел наклона в градусах (`tilt.pointerMax`). Курсор за пределами
 * карты не наклоняет её сильнее предела: указатель может уйти с карты раньше,
 * чем придёт событие ухода, и без ограничения карта успела бы вывернуться.
 */
export function cardTilt(box: TiltBox, pointerX: number, pointerY: number, cap: number): Tilt {
  const dx = (pointerX - (box.left + box.width / 2)) / (box.width / 2);
  const dy = (pointerY - (box.top + box.height / 2)) / (box.height / 2);
  /* `+ 0` приводит минус-ноль к нулю: `-dy * cap` при курсоре ровно посередине
     даёт `-0`, для CSS это тот же ноль, а вот сравнение с нулём на нём
     спотыкается. Для остальных значений прибавление нуля ничего не меняет. */
  const clamp = (value: number) => Math.max(-cap, Math.min(cap, value)) + 0;
  /* Знак у `x` обратный: курсор ниже середины — верхний край карты уходит от
     зрителя, а это отрицательный поворот вокруг горизонтали. */
  return { x: clamp(-dy * cap), y: clamp(dx * cap) };
}
