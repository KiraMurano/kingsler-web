/**
 * Какой копией арта показывать карту.
 *
 * Исходники карт — 1024×1536, и распакованный битмап каждого весит шесть
 * мегабайт независимо от того, каким размером карту вывели: память платит по
 * размеру файла, а не по размеру на экране. Поверхностей же у одной и той же
 * карты много, и они несопоставимы — от крупного плана в описании (176 px
 * макета) до строки кодекса (40). Гонять везде исходник значит держать
 * двадцатипятикратный запас там, где он не виден.
 *
 * Копии лежат рядом с оригиналами и сделаны `scripts/gen-card-art.mjs` — там
 * же объяснено, откуда взялись ступени. Здесь остаётся правило выбора:
 *
 *   256 → до  57 px макета
 *   512 → до 113 px макета
 *   768 → до 170 px макета
 *
 * Числа — это ширина копии, делённая на 4.5: столько физических пикселей на
 * пиксель макета нужно, чтобы карта не мылилась на 4K (там требуется 3.0) и на
 * 5K Retina (4.0). Размеры поверхностей мерены живьём, а не выведены из CSS.
 *
 * Оригинал остаётся у плиток лендинга: там арт растянут по ширине 308 px
 * макета, и любая копия была бы шагом назад.
 */

/** Ширины готовых копий. Больше нет — за ними в `gen-card-art.mjs`. */
export type CardArtWidth = 256 | 512 | 768;

const CARDS = '/assets/cards/';

/**
 * Путь к копии нужной ширины. Всё, что не арт карты, возвращается как есть:
 * аватары и картинки интерфейса живут по своим правилам, и подставлять им
 * несуществующий суффикс значит получить битую картинку.
 *
 * `undefined` проходит насквозь: у карт-действий арта нет вовсе, и заставлять
 * каждое место вокруг городить проверку — значит разложить её по шести файлам.
 * Перегрузки нужны, чтобы строка на входе по-прежнему давала строку: иначе
 * `CARD_BACK` и прочие заведомо существующие пути стали бы «возможно
 * отсутствующими» на ровном месте.
 */
export function cardArt(src: string, width: CardArtWidth): string;
export function cardArt(src: string | undefined, width: CardArtWidth): string | undefined;
export function cardArt(src: string | undefined, width: CardArtWidth): string | undefined {
  if (!src || !src.startsWith(CARDS) || !src.endsWith('.webp')) return src;
  return `${src.slice(0, -'.webp'.length)}-${width}.webp`;
}

/**
 * Ширина, которой рисует карты стол, — и которую греет `preloadAssets`.
 *
 * Объявлена здесь, а не у каждого из них, потому что разойтись им нельзя: если
 * прогрев греет одну копию, а стол просит другую, прогрев превращается в
 * лишнюю загрузку, и карта всё равно проявляется с задержкой — то есть ломается
 * ровно то, ради чего прогрев и заведён, и ломается молча.
 */
export const TABLE_ART_WIDTH: CardArtWidth = 768;
