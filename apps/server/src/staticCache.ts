/**
 * Сколько браузеру держать статику.
 *
 * По умолчанию `express.static` ставит `max-age=0`, и это была не экономия
 * места, а лишний сетевой круг на КАЖДЫЙ показ каждой картинки: байты
 * возвращались как `304 Not Modified`, но ждать ответа всё равно приходилось —
 * ровно в тот момент, когда карту кладут на стол, и арт проявлялся уже после
 * неё. Локально этого не видно: файл берётся с диска.
 *
 * Отдельным модулем, а не внутри `app.ts`: правило чистое и проверяемое, а
 * `app.ts` при импорте поднимает аутентификацию и требует ключи окружения.
 */
import type express from 'express';

/** Сутки. Столько живут в кэше арты, аватары и шрифт. */
export const STATIC_MAX_AGE_S = 60 * 60 * 24;

/** Год. Столько живут файлы, у которых имя содержит хэш содержимого. */
export const IMMUTABLE_MAX_AGE_S = 60 * 60 * 24 * 365;

/** Собранный бандл: Vite называет их по хэшу содержимого. */
const HASHED_BUNDLE = /[\\/]assets[\\/]index-[A-Za-z0-9_-]+\.(js|css)$/;

/**
 * Три политики, потому что файлы трёх разных сортов:
 *
 *  - `index.html` не кэшируется вовсе: в нём записаны имена собранных бандлов,
 *    и закэшированный он увёл бы игрока на прошлую версию после деплоя.
 *  - Бандлы `assets/index-*.js|css` названы по хэшу содержимого: их содержимое
 *    не меняется никогда — меняется имя. Год и `immutable`.
 *  - Всё остальное — арты, аватары, шрифт — имена имеет постоянные, поэтому
 *    сутки, а не год: свежий арт доедет до игрока на следующий день, а не через
 *    год. `ETag` при этом никуда не девается, так что и внутри этих суток
 *    обновление подхватится, просто через проверку.
 */
export function cacheHeaders(res: express.Response, filePath: string): void {
  if (filePath.endsWith('index.html')) {
    res.setHeader('Cache-Control', 'no-cache');
    return;
  }

  res.setHeader(
    'Cache-Control',
    HASHED_BUNDLE.test(filePath)
      ? `public, max-age=${IMMUTABLE_MAX_AGE_S}, immutable`
      : `public, max-age=${STATIC_MAX_AGE_S}`
  );
}
